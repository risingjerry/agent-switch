pub const HUB_ID: &str = "agent-hub";

pub fn detected_apps(paths: &Paths) -> Vec<&'static str> {
    let real = paths.targets_real_user();
    let cmd = |c: &str| real && which(c).is_some();
    let mut out = Vec::new();
    let codex_dir = paths.codex_config.parent().unwrap();
    if codex_dir.exists() || paths.codex_config.exists() || cmd("codex") {
        out.push("codex");
    }
    if paths.claude_global_instructions.parent().unwrap().exists() || paths.claude_config.exists() || cmd("claude") {
        out.push("claude");
    }
    if paths.hermes_config.parent().unwrap().exists()
        || paths.hermes_config.exists()
        || paths.hermes_soul.exists()
        || cmd("hermes")
    {
        out.push("hermes");
    }
    if paths.claude_desktop_config.exists()
        || paths.user_home.join("Applications").join("Claude.app").exists()
        || (real && Path::new("/Applications/Claude.app").exists())
    {
        out.push("claude_desktop");
    }
    out
}

/// The binary that wrappers exec. Overridable for packaging and tests.
pub fn self_binary() -> String {
    if let Ok(v) = std::env::var("AGENT_SWITCH_BIN")
        && !v.is_empty()
    {
        return v;
    }
    std::env::current_exe()
        .ok()
        .and_then(|p| fs::canonicalize(p).ok())
        .map(|p| p.to_string_lossy().into_owned())
        .unwrap_or_else(|| "agent-switch".into())
}

fn shell_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\\''"))
}

/// One wrapper per projected entry; native configs keep pointing at the same
/// stable path no matter where the binary is installed.
pub struct Wrapper {
    pub id: String,
    pub path: PathBuf,
    pub content: String,
}

pub fn wrappers(config: &Config, paths: &Paths) -> Vec<Wrapper> {
    let bin = shell_quote(&self_binary());
    let mut out: Vec<Wrapper> = config
        .tools
        .iter()
        .filter(|t| t.enabled && t.mode == Mode::Direct)
        .map(|t| Wrapper {
            id: t.id.clone(),
            path: paths.wrapper_dir.join(t.wrapper_name()),
            content: format!(
                "#!/bin/sh\n# Generated by Agent Switch. Do not edit; run `agent-switch reconcile`.\nexec {bin} run {} \"$@\"\n",
                shell_quote(&t.id)
            ),
        })
        .collect();
    if config.tools.iter().any(|t| t.enabled && t.mode == Mode::Hub) {
        out.push(Wrapper {
            id: HUB_ID.into(),
            path: paths.wrapper_dir.join("mcp-hub"),
            content: format!(
                "#!/bin/sh\n# Generated by Agent Switch. Do not edit; run `agent-switch reconcile`.\nexec {bin} hub \"$@\"\n"
            ),
        });
    }
    out
}

pub fn desired_for_app(config: &Config, app: &str, paths: &Paths) -> Desired {
    let mut desired = Desired::new();
    let mut hub = false;
    for tool in config.tools_for_app(app) {
        match tool.mode {
            Mode::Direct => {
                let command = paths.wrapper_dir.join(tool.wrapper_name()).to_string_lossy().into_owned();
                desired.insert(tool.id.clone(), Spec { command, args: vec![] });
            }
            Mode::Hub => hub = true,
        }
    }
    if hub {
        let command = paths.wrapper_dir.join("mcp-hub").to_string_lossy().into_owned();
        desired.insert(HUB_ID.into(), Spec { command, args: vec![app.to_string()] });
    }
    desired
}

pub struct Finding {
    pub severity: &'static str,
    pub target: String,
    pub message: String,
}

pub struct Change {
    pub target: String,
    pub path: Option<PathBuf>,
    pub action: &'static str,
    pub detail: String,
}

pub struct Report {
    pub findings: Vec<Finding>,
    pub changes: Vec<Change>,
    pub secrets: secrets::Report,
}

impl Report {
    pub fn blocked(&self) -> bool {
        self.findings.iter().any(|f| f.severity == "error")
    }

    pub fn to_value(&self) -> Value {
        let value = json!({
            "blocked": self.blocked(),
            "driftCount": self.changes.len(),
            "findings": self.findings.iter().map(|f| json!({
                "severity": f.severity, "target": f.target, "message": crate::redact::text(&f.message),
            })).collect::<Vec<_>>(),
            "changes": self.changes.iter().map(|c| json!({
                "target": c.target,
                "path": c.path.as_ref().map(|p| p.to_string_lossy().into_owned()),
                "action": c.action,
                "detail": c.detail,
            })).collect::<Vec<_>>(),
            "secrets": self.secrets.to_value(),
        });
        crate::redact::mapping(&value)
    }

    pub fn human(&self) -> String {
        let mut lines = vec![
            format!("Agent Switch status: {}", if self.blocked() { "blocked" } else { "ok" }),
            format!("Drift changes: {}", self.changes.len()),
            format!(
                "Missing secrets: {}",
                if self.secrets.missing.is_empty() { "none".into() } else { self.secrets.missing.join(", ") }
            ),
        ];
        for f in &self.findings {
            lines.push(format!("- {}: {}: {}", f.severity, f.target, f.message));
        }
        for c in &self.changes {
            let path = c.path.as_ref().map(|p| format!(" {}", p.display())).unwrap_or_default();
            lines.push(format!("- change: {}:{path} {} {}", c.target, c.action, c.detail));
        }
        lines.join("\n") + "\n"
    }
}

fn unpinned_npx(command: &str, args: &[String]) -> Option<String> {
    let name = Path::new(command).file_name()?.to_string_lossy();
    if name != "npx" && name != "npx.cmd" {
        return None;
    }
    let package = args.iter().find(|a| !a.starts_with('-'))?;
    if let Some(scoped) = package.strip_prefix('@') {
        return (!scoped.contains('@')).then(|| package.clone());
    }
    (!package.contains('@')).then(|| package.clone())
}

fn is_executable(path: &Path) -> bool {
    fs::metadata(path).map(|m| m.is_file() && m.permissions().mode() & 0o111 != 0).unwrap_or(false)
}

type Renderer = fn(&str, &Desired, &Paths) -> Result<String>;

/// Semantic comparison for JSON targets; text targets compare rendered bytes.
fn in_sync(app: &str, current: &str, desired: &Desired) -> bool {
    matches!(app, "claude" | "claude_desktop") && render::json_in_sync(current, desired)
}
type Target = (&'static str, fn(&Paths) -> &Path, Renderer);

fn targets() -> [Target; 4] {
    [
        ("claude", |p| &p.claude_config, |t, d, _| render::json_config(t, d)),
        ("claude_desktop", |p| &p.claude_desktop_config, |t, d, _| render::json_config(t, d)),
        ("codex", |p| &p.codex_config, |t, d, p| render::codex_config(t, d, Some(&p.codex_instructions))),
        ("hermes", |p| &p.hermes_config, |t, d, _| Ok(render::hermes_config(t, d))),
    ]
}

pub fn run(config: &Config, paths: &Paths) -> Result<Report> {
    let mut findings = Vec::new();
    let mut changes = Vec::new();
    let apps = detected_apps(paths);
    let secret_report = secrets::check(config)?;
    if !secret_report.missing.is_empty() {
        findings.push(Finding {
            severity: "warning",
            target: "secrets".into(),
            message: format!("missing required secret name(s): {}", secret_report.missing.join(", ")),
        });
    }
    for tool in &config.tools {
        if let Some(pkg) = unpinned_npx(&tool.command, &tool.args) {
            findings.push(Finding {
                severity: "warning",
                target: tool.id.clone(),
                message: format!("npx package is not version-pinned: {pkg}"),
            });
        }
    }
    let wanted = wrappers(config, paths);
    for w in &wanted {
        let current = fs::read_to_string(&w.path).ok();
        if current.as_deref() != Some(w.content.as_str()) || !is_executable(&w.path) {
            changes.push(Change {
                target: "wrappers".into(),
                path: Some(w.path.clone()),
                action: "write",
                detail: format!("wrapper for {} is missing, outdated or not executable", w.id),
            });
        }
    }
    let wanted_paths: BTreeSet<&PathBuf> = wanted.iter().map(|w| &w.path).collect();
    for stale in stale_wrappers(paths) {
        if !wanted_paths.contains(&stale) {
            changes.push(Change {
                target: "wrappers".into(),
                path: Some(stale),
                action: "delete",
                detail: "stale or disabled MCP wrapper".into(),
            });
        }
    }
    for (target, path, desired, _) in instructions::targets(paths, &apps)? {
        if read_text(&path)? != desired {
            changes.push(Change {
                action: if path.exists() { "update" } else { "create" },
                path: Some(path),
                detail: format!("{target} managed instructions differ"),
                target: target.into(),
            });
        }
    }
    for (app, path_of, renderer) in targets() {
        if !apps.contains(&app) {
            continue;
        }
        let path = path_of(paths);
        let current = read_text(path)?;
        let desired = desired_for_app(config, app, paths);
        if in_sync(app, &current, &desired) {
            continue;
        }
        match renderer(&current, &desired, paths) {
            Err(e) => findings.push(Finding { severity: "error", target: app.into(), message: e }),
            Ok(rendered) if rendered != current => changes.push(Change {
                target: app.into(),
                path: Some(path.to_path_buf()),
                action: if path.exists() { "update" } else { "create" },
                detail: format!("{app} agent-owned MCP projection differs"),
            }),
            Ok(_) => {}
        }
    }
    Ok(Report { findings, changes, secrets: secret_report })
}

fn stale_wrappers(paths: &Paths) -> Vec<PathBuf> {
    let Ok(entries) = fs::read_dir(&paths.wrapper_dir) else { return Vec::new() };
    let mut out: Vec<PathBuf> = entries
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| p.is_file() && p.file_name().is_some_and(|n| n.to_string_lossy().starts_with("mcp-")))
        .collect();
    out.sort();
    out
}

pub struct ApplySummary {
    pub changed: usize,
    pub unchanged: usize,
    pub blocked: usize,
}

impl ApplySummary {
    pub fn to_value(&self) -> Value {
        json!({"changed": self.changed, "unchanged": self.unchanged, "blocked": self.blocked})
    }
}

pub fn apply(config: &Config, paths: &Paths) -> Result<(ApplySummary, Report)> {
    let pre = run(config, paths)?;
    if pre.blocked() {
        return Ok((ApplySummary { changed: 0, unchanged: 0, blocked: 1 }, pre));
    }
    let mut summary = ApplySummary { changed: 0, unchanged: 0, blocked: 0 };
    let mut count = |changed: bool| {
        if changed { summary.changed += 1 } else { summary.unchanged += 1 }
    };
    let apps = detected_apps(paths);
    for r in instructions::write(paths, &apps)? {
        count(r.changed);
    }
    crate::util::ensure_private_dir(&paths.agent_home);
    crate::util::ensure_private_dir(&paths.wrapper_dir);
    let wanted = wrappers(config, paths);
    for w in &wanted {
        let r = write_if_changed(&w.path, &w.content, Some(0o755), Some(&paths.backup_dir))?;
        // Content may already match while the mode does not.
        if !r.changed && !is_executable(&w.path) {
            fs::set_permissions(&w.path, fs::Permissions::from_mode(0o755)).map_err(|e| e.to_string())?;
            count(true);
        } else {
            count(r.changed);
        }
    }
    let wanted_paths: BTreeSet<&PathBuf> = wanted.iter().map(|w| &w.path).collect();
    for stale in stale_wrappers(paths) {
        if !wanted_paths.contains(&stale) {
            fs::remove_file(&stale).map_err(|e| format!("failed to remove {}: {e}", stale.display()))?;
            count(true);
        }
    }
    for (app, path_of, renderer) in targets() {
        if !apps.contains(&app) {
            continue;
        }
        let path = path_of(paths);
        let current = read_text(path)?;
        let desired = desired_for_app(config, app, paths);
        if in_sync(app, &current, &desired) {
            count(false);
            continue;
        }
        let rendered = renderer(&current, &desired, paths)?;
        count(write_if_changed(path, &rendered, None, Some(&paths.backup_dir))?.changed);
    }
    let post = run(config, paths)?;
    Ok((summary, post))
}
